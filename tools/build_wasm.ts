import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
for (const [command, args] of [
  ["rustup", ["target", "add", "wasm32-unknown-unknown"]],
  [
    "cargo",
    [
      "build",
      "--manifest-path",
      "rust/Cargo.toml",
      "--target",
      "wasm32-unknown-unknown",
      "--release",
      "--locked",
    ],
  ],
] as const) {
  const result = spawnSync(command, args, { cwd: root, stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} failed (${result.status})`);
}
const bytes = readFileSync(
  path.join(root, "rust/target/wasm32-unknown-unknown/release/hiplot_kernels.wasm"),
);
const destination = path.join(root, "src/wasm/embedded.generated.ts");
mkdirSync(path.dirname(destination), { recursive: true });
const source = `// Generated by tools/build_wasm.ts from rust/src/lib.rs.\nexport default ${JSON.stringify(bytes.toString("base64"))};\n`;
if (!existsSync(destination) || readFileSync(destination, "utf8") !== source) {
  writeFileSync(destination, source);
}
